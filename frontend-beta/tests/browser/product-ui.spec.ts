test("AutoEval begins with one HF input and never fakes inspection or evaluation", async ({ page }) => {
 await page.getByRole("navigation").getByRole("link", { name: "AutoEval" }).click();
 await expect(page.getByRole("heading", { name: "AutoEval", exact: true })).toBeVisible();
 await expect(page.locator("input")).toHaveCount(1);
 const posts: string[] = [];
 page.on("request", r => { if (r.method() === "POST") posts.push(r.url()); });
 await page.getByLabel("Hugging Face model URL or repository ID").fill("https://evil.example/owner/model");
 await page.getByRole("button", { name: "Prepare inspection", exact: true }).click();
 await expect(page.getByRole("alert")).toContainText("Use owner/model");
 await expect(page.getByRole("status")).toHaveCount(0);
 await page.getByLabel("Hugging Face model URL or repository ID").fill("https://huggingface.co/SlayerLab/GoLLeM-v6-250M");
 await page.getByRole("button", { name: "Prepare inspection", exact: true }).click();
 await expect(page.getByRole("status")).toContainText("Repository format checked: SlayerLab/GoLLeM-v6-250M");
 await expect(page.getByRole("status")).toContainText("No revision has been resolved");
 await expect(page.getByRole("button", { name: "Inspect model — service not connected" })).toBeDisabled();
 await expect(page.getByText("Unavailable — no evaluation exists", { exact: true })).toBeVisible();
 expect(posts).toEqual([]);
 await page.reload();
 await expect(page.getByRole("status")).toHaveCount(0);
 await expect(page.getByLabel("Hugging Face model URL or repository ID")).toHaveValue("");
});
