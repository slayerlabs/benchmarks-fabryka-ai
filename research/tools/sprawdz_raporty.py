def jednostki(linie):
    """Akapity (lista (nr_linii, tekst)); wiersz tabeli, nagłówek i punkt listy zaczynają nowy akapit."""
    akapity, biezacy, w_kodzie = [], [], False
    for nr, linia in enumerate(linie, 1):
        s = linia.strip()
        if s.startswith("```"):
            w_kodzie = not w_kodzie
            if biezacy:
                akapity.append(biezacy)
            biezacy = []
            continue
        if w_kodzie:
            continue
        if not s:
            if biezacy:
                akapity.append(biezacy)
            biezacy = []
            continue
        if s.startswith(("|", "#", "- ", "* ")) or re.match(r"\d+\.\s", s):
            if biezacy:
                akapity.append(biezacy)
            biezacy = [(nr, linia)]
            if s.startswith(("|", "#")):
                akapity.append(biezacy)
                biezacy = []
            continue
        biezacy.append((nr, linia))
    if biezacy:
        akapity.append(biezacy)
    return akapity


def zdania(akapit):
    """[(nr_linii_startu, zdanie)] z akapitu sklejonego spacjami."""
    tekst, starty = "", []
    for nr, l in akapit:
        starty.append((len(tekst), nr))
        tekst += bez_kodu(l).strip() + " "
    out, poz = [], 0
    for kawalek in ZDANIE.split(tekst):
        i = tekst.find(kawalek, poz)
        nr = max(n for off, n in starty if off <= max(i, 0))
        out.append((nr, kawalek.strip()))
        poz = i + len(kawalek)
    return [(n, z) for n, z in out if z]


def wylaczone(plik, sekcja, regula):
    for p, s, reg, _ in WYLACZENIA:
        if p == plik and regula in reg and (s is None or (sekcja or "").startswith(s)):
            return True
    return False


# ---------- (l) tabele: werdykt w komórce wobec z/t z tego samego wiersza, kolumna „po Holmie” wobec rodziny tabeli ----------
_KOL_Z = re.compile(r"^z\b(?!\s*[(:].*\bt\b)", re.IGNORECASE)
_KOL_T = re.compile(r"^t\b", re.IGNORECASE)
_KOL_WERDYKT = re.compile(r"^(?:werdykt|verdict)\b(?!.*(?:/|Holm))", re.IGNORECASE)
_KOL_HOLM = re.compile(r"^(?:po Holmie|after Holm|Holm)\b", re.IGNORECASE)
_KOL_WERDYKT_HOLMA = re.compile(r"^(?:werdykt|verdict)\b.*Holm", re.IGNORECASE)
_KOL_P_HOLMA = re.compile(r"^p[ _]Holm", re.IGNORECASE)
_KOMORKA_P = re.compile(r"^\s*(\d+)[.,](\d+)\s*$")
_KOMORKA_LICZBA = re.compile(r"^\s*(?:([zt])\s*=\s*)?([−-]?)(\d+)(?:[.,](\d+))?(?:\s*,\s*df\s*=?\s*(\d+))?\s*$", re.IGNORECASE)
_KOMORKA_SLOWO = re.compile(rf"^\s*\**({_SLOWO_Z})\**\s*$", re.IGNORECASE)
_KOMORKA_HOLM = re.compile(rf"^\s*(tak|nie|yes|no)\b(?:\s*\(\s*({_SLOWO_Z})\s*\))?", re.IGNORECASE)


def _bloki_tabel(linie):
    """[(nr nagłówka, [nr wierszy danych])] dla każdej tabeli markdown (nagłówek, separator, wiersze)."""
    out, i = [], 0
    while i < len(linie):
        if (linie[i].lstrip().startswith("|") and i + 1 < len(linie)
                and re.fullmatch(r"\s*\|[\s:|-]+\|\s*", linie[i + 1])):
            j = i + 2
            while j < len(linie) and linie[j].lstrip().startswith("|"):
                j += 1
            out.append((i, list(range(i + 2, j))))
            i = j
        else:
            i += 1
    return out


def _komorka_statystyki(tekst):
    """(wartość, cyfry, df z komórki albo None, „z”/„t” z zapisu `z = …`/`t = …` albo None) z komórki `−3,03`,
    `t = 4,47, df 134`; None, gdy to nie liczba."""
    m = _KOMORKA_LICZBA.match(tekst.replace("**", ""))
    if not m:
        return None
    return (_wartosc_z(m.group(2), m.group(3), m.group(4)), len(m.group(4) or ""),
            (int(m.group(5)) if m.group(5) else None), (m.group(1) or "").lower() or None)


def _df_sekcji(linie, h, akapitow=2):
    """Jedno df zapisane w `akapitow` akapitach tuż nad tabelą z linii h (np. opis tabeli, a pod nim akapit
    „Conclusion for the table”), bez przechodzenia przez inną tabelę ani nagłówek; albo None."""
    j, tekst = h, []
    for _ in range(akapitow):
        while j > 0 and not linie[j - 1].strip():
            j -= 1
        if j == 0 or linie[j - 1].lstrip().startswith(("|", "#")):
            break
        while j > 0 and linie[j - 1].strip() and not linie[j - 1].lstrip().startswith(("|", "#")):
            j -= 1
            tekst.append(linie[j])
    return df_z_linii(" ".join(tekst))


def _p_przedzial(rodzaj, wartosc, cyfr, df):
    """Dwustronne p na obu końcach przedziału zaokrąglenia |wartości|: (p przy |x| + h, p przy |x| − h)."""
    h = 0.5 * 10 ** (-cyfr)
    a = [abs(wartosc) + h, max(abs(wartosc) - h, 0.0)]
    if rodzaj == "z":
        return tuple(math.erfc(x / math.sqrt(2)) for x in a)
    return tuple(liczby.p_t(x, df) for x in a)


def tabela_problemy(linie):
    """(l) [(indeks linii, opis)]: (1) słowo werdyktu w kolumnie „werdykt/verdict” wobec z albo t z najbliższej
    kolumny z/t na lewo w tym samym wierszu (t z df z kolumny „df”, z nagłówka `(df = N)`, z komórki albo z akapitu
    nad tabelą); (2) flaga „po Holmie”/„after Holm” (tak/nie i werdykt w nawiasie) wobec Holma liczonego na p
    wszystkich wierszy tabeli z tej samej kolumny z/t (rodzina = tabela). Przy zaokrągleniu, które leży na progu,
    bramka milczy."""
    problemy = []
    for h, wiersze in _bloki_tabel(linie):
        nag = komorki(linie[h])
        stat = {k: ("z" if _KOL_Z.match(c) else "t") for k, c in enumerate(nag) if _KOL_Z.match(c) or _KOL_T.match(c)}
        for k in range(len(nag)):  # kolumna bez z/t w nagłówku („test”), której komórki zapisują `z = …`/`t = …`
            komorki_k = [komorki(linie[i])[k] for i in wiersze if k < len(komorki(linie[i]))]
            if k not in stat and any(re.match(r"\s*[zt]\s*=", x) for x in komorki_k):
                stat[k] = "?"
        problemy += _werdykt_z_p_holma(linie, nag, wiersze)
        if not stat:
            continue
        df_kol = [k for k, c in enumerate(nag) if c.strip().lower() == "df"]
        df_nag = {k: int(m.group(1)) for k in stat for m in [re.search(r"df\s*=\s*(\d+)", nag[k])] if m}

        def zrodlo(k):  # najbliższa kolumna z/t na lewo od k
            lewo = [s for s in stat if s < k]
            return max(lewo) if lewo else None

        def df_wiersza(i, s, df_kom):
            if stat[s] == "z":
                return 0
            if stat[s] == "?":
                return None
            if df_kom is not None:
                return df_kom
            if s in df_nag:
                return df_nag[s]
            prawo = [d for d in df_kol if d > s]
            k = min(prawo) if prawo else (max(df_kol) if df_kol else None)
            if k is not None:
                c = komorki(linie[i])
                return int(c[k]) if k < len(c) and c[k].strip().isdigit() else None
            df = df_kontekstu(linie, i)
            return df if df is not None else _df_sekcji(linie, h)

        wartosci = {}  # (wiersz, kolumna statystyki) -> (wartość, cyfr, df, „z”/„t”)
        for i in wiersze:
            c = komorki(linie[i])
            for s in stat:
                v = _komorka_statystyki(c[s]) if s < len(c) else None
                if v is None:
                    continue
                rodzaj = v[3] or stat[s]
                if rodzaj == "?":
                    continue
                df = 0 if rodzaj == "z" else (v[2] if v[2] is not None else df_wiersza(i, s, None))
                if df is None or (rodzaj == "t" and df <= 0):
                    continue
                wartosci[(i, s)] = (v[0], v[1], df, rodzaj)
        for k, nazwa in enumerate(nag):
            s = zrodlo(k)
            if s is None or any(s < x < k for x in stat):
                continue
            if _KOL_WERDYKT.match(nazwa):
                for i in wiersze:
                    c = komorki(linie[i])
                    m = _KOMORKA_SLOWO.match(c[k]) if k < len(c) else None
                    if not m or (i, s) not in wartosci:
                        continue
                    x, cyfr, df, rodzaj = wartosci[(i, s)]
                    oczek = {liczby.werdykt_p(p) for p in _p_przedzial(rodzaj, x, cyfr, df)}
                    if len(oczek) == 1 and _nazwa_werdyktu(m.group(1)) != (o := oczek.pop()):
                        problemy.append((i, f"(l) {rodzaj} {c[s].strip()}{f' (df {df})' if rodzaj == 't' else ''} "
                                            f"→ {o}, w kolumnie „{nazwa}”: {m.group(1)}"))
            elif _KOL_HOLM.match(nazwa):
                pelna = bool(re.match(r"(?:po Holmie|after Holm)\b", nazwa, re.IGNORECASE))  # rodzina = tabela
                # wiersz bez tak/nie (np. „outside the family (k < 3)”) nie należy do rodziny
                rodzina = [i for i in wiersze if (i, s) in wartosci and k < len(komorki(linie[i]))
                           and _KOMORKA_HOLM.match(komorki(linie[i])[k])]
                if len(rodzina) < 2:
                    continue
                przedzialy = [_p_przedzial(wartosci[(i, s)][3], *wartosci[(i, s)][:3]) for i in rodzina]
                dol, gora = liczby.holm([a for a, _ in przedzialy]), liczby.holm([b for _, b in przedzialy])
                for i, a, b in zip(rodzina, dol, gora):
                    c = komorki(linie[i])
                    m = _KOMORKA_HOLM.match(c[k]) if k < len(c) else None
                    if not m:
                        continue
                    flagi = {"tak" if p <= liczby.P_PRAWDOPODOBNE else "nie" for p in (a, b)}
                    jest = "tak" if m.group(1).lower() in ("tak", "yes") else "nie"
                    if not pelna and (jest == "nie" or "nie" not in flagi):
                        # kolumna „Holm …”: rodzina może być większa niż wiersze tabeli (ranking 67 paradygmatów
                        # pokazany częściowo), a Holm na podzbiorze daje p nie większe, więc łapie tylko „tak”,
                        # którego nie daje nawet rodzina z samych wierszy tabeli
                        continue
                    if len(flagi) == 1 and jest != (o := flagi.pop()):
                        problemy.append((i, f"(l) Holm w rodzinie {len(rodzina)} wierszy → {o}, w kolumnie „{nazwa}”: "
                                            f"{m.group(1)}"))
                    slowa = {liczby.werdykt_p(p) for p in (a, b)}
                    if m.group(2) and len(slowa) == 1 and _nazwa_werdyktu(m.group(2)) != (o := slowa.pop()):
                        problemy.append((i, f"(l) werdykt z p Holma → {o}, w kolumnie „{nazwa}”: {m.group(2)}"))
    return problemy


def _werdykt_z_p_holma(linie, nag, wiersze):
    """(l) kolumna „werdykt po Holmie”/„verdict after Holm” wobec p z najbliższej kolumny „p Holm…” na lewo."""
    problemy = []
    for k, nazwa in enumerate(nag):
        if not _KOL_WERDYKT_HOLMA.match(nazwa):
            continue
        lewo = [j for j in range(k) if _KOL_P_HOLMA.match(nag[j])]
        if not lewo:
            continue
        j = max(lewo)
        for i in wiersze:
            c = komorki(linie[i])
            m = _KOMORKA_SLOWO.match(c[k]) if k < len(c) else None
            mp = _KOMORKA_P.match(c[j]) if j < len(c) else None
            if not m or not mp:
                continue
            p, h = float(f"{mp.group(1)}.{mp.group(2)}"), 0.5 * 10 ** (-len(mp.group(2)))
            oczek = {liczby.werdykt_p(x) for x in (max(p - h, 0.0), p + h)}
            if len(oczek) == 1 and _nazwa_werdyktu(m.group(1)) != (o := oczek.pop()):
                problemy.append((i, f"(l) p Holma {c[j].strip()} → {o}, w kolumnie „{nazwa}”: {m.group(1)}"))
    return problemy


def sprawdz_tekst(plik, linie, liczby, zb):
    bledy = []
    sekcja, sekcje = None, {}
    for nr, l in enumerate(linie, 1):
        if l.startswith("#"):
            sekcja = l.strip()
        sekcje[nr] = sekcja
    w_kodzie = False
    bench_pliku = benchmark_pliku(plik, liczby)
    for nr, l in enumerate(linie, 1):
        if l.strip().startswith("```"):
            w_kodzie = not w_kodzie
            continue
        if w_kodzie:
            continue
        # Wyjątek i wyłączenia dotyczą liczb spoza LICZBY.json. Werdykt wobec |z| w tej linii zostaje.
        if WYJATEK_A not in l and not wylaczone(plik, sekcje[nr], "a"):
            bench = benchmarki_w_tekscie(bez_kodu(l), liczby) | ({bench_pliku} if bench_pliku else set())
            kropka, test_domyslny = file_number_format(plik)
            for tekst, rodzaj in niepasujace_liczby(l, zb, liczby["aliasy"], sorted(bench), kropka=kropka,
                                                    test_domyslny=test_domyslny):
                opis = {"z": "jako z (×SE)", "t": "jako t (pole z porównania albo wartość)", "skalowana": "jako pkt/% (×100)", "surowa": "jako wartość"}[rodzaj]
                bledy.append((plik, nr, f"(a) {tekst} nie odpowiada żadnej liczbie z LICZBY.json {opis}"))
        for problem in z_verdict_problems(l):
            bledy.append((plik, nr, problem))
        for problem in t_verdict_problems(l, df_kontekstu(linie, nr - 1), liczby):
            bledy.append((plik, nr, problem))
    # LICZBY.md wypisuje werdykt główny porównania (przy klastrach z t, df nie ma w tabeli) obok z par: to nie raport
    for i, problem in ([] if plik == "results/LICZBY.md" else tabela_problemy(linie)):
        bledy.append((plik, i + 1, problem))
    akapity = jednostki(linie)
    teksty = [" ".join(bez_kodu(l) for _, l in a) for a in akapity]
    for i, akapit in enumerate(akapity):
        nr0 = akapit[0][0]
        tekst_akapitu = teksty[i]
        surowy_akapit = " ".join(l for _, l in akapit)
        sasiedzi = " ".join(teksty[j] for j in range(i - _OKNO_K, i + _OKNO_K + 1) if j != i and 0 <= j < len(teksty))
        if holm_bez_paradygmatow(tekst_akapitu, sasiedzi):
            bledy.append((plik, nr0, "(k) liczba wyników po Holmie bez liczby po paradygmatach, a ten albo sąsiedni "
                                     "akapit opisuje odczyt po paradygmatach: zdanie o zjawiskach stoi na samych parach"))
        wstep = re.match(r"\s*(?:[-*]\s+|\d+\.\s+)?\*\*(.+?)\*\*", tekst_akapitu)
        wstep = wstep.group(1) if wstep else ""
        ma_liczby = bool(re.search(r"\d", tekst_akapitu))
        for nr, zd in zdania(akapit):
            if (ma_liczby and not wylaczone(plik, sekcje[nr0], "b") and WYJATEK_B not in surowy_akapit
                    and ocena_bez_dowodu(zd, wstep)):
                bledy.append((plik, nr, f"(b) ocena różnicy bez SE/z/werdyktu: „{zd[:90]}”"))
            if wylaczone(plik, sekcje[nr0], "c"):
                continue
            for klauzula in re.split(r"[;|]", zd):
                for test, dekl, dane in za_mocny_werdykt(klauzula, tekst_akapitu, liczby, plik, zd):
                    bledy.append((plik, nr, f"(c) „{dekl}” przy {test}, a najmocniejszy werdykt w LICZBY.json to „{dane}”"))
    return bledy


# ---------- bramki raportów z metadanymi (LICZBY.json "raporty"; starsze raporty ich nie mają) ----------

SLOWO_WERDYKTU = re.compile(r"\b(certain|probable|pewn\w*|prawdopodobn\w*)\b", re.IGNORECASE)
BEZ_WERDYKTU = {"nierozstrzygalne", "undetermined"}
NA_TOKEN = re.compile(r"\b(per[ -]token|per[ -]byte|na token|na bajt)\b", re.IGNORECASE)


def bramki_raportu(meta, linie, liczby):
    """Gates for a report on a multi-paradigm set (BLiMP, MultiBLiMP, MMLU):
    (d) a verdict word needs an SE/z clustered by paradigm in LICZBY.json, and a ranking of
        more than one paradigm needs a Holm field for every paradigm;
    (e) a group with < 3 members may only be "undetermined" at the paradigm level: in the metadata and in the
        clustered-verdict column of its table row (meta "kolumna_werdyktu_klastrowego"; the pair-level verdict
        in the same row is a claim about the pairs and stays); without that key, anywhere in the row;
    (f) models with different tokenizers need a per-token comparison in LICZBY.json and in the text."""
    plik, bledy = meta["plik"], []
    tekst = "\n".join(linie)
    por = {p["id"]: p for p in liczby["porownania"]}
    if meta.get("wieloparadygmatowy") and SLOWO_WERDYKTU.search(tekst):
        k = por.get(meta.get("porownanie_klastrowe") or "")
        if not k or k.get("se") is None or k.get("z") is None:
            bledy.append((plik, 0, "(d) werdykt na zbiorze wieloparadygmatowym bez SE/z klastrowanego po paradygmatach"))
        holm = meta.get("holm") or {}
        if meta.get("k_paradygmatow", 0) > 1 and (len(holm) < meta["k_paradygmatow"]
                                                   or not all(isinstance(v, bool) for v in holm.values())):
            bledy.append((plik, 0, "(d) ranking paradygmatów bez poprawki Holma dla każdego paradygmatu"))
    kolumna = meta.get("kolumna_werdyktu_klastrowego")
    for g in meta.get("grupy", []):
        if g["k"] >= 3:
            continue
        if g["werdykt"] not in BEZ_WERDYKTU:
            bledy.append((plik, 0, f"(e) grupa {g['nazwa']} ma {g['k']} członków, a werdykt „{g['werdykt']}”"))
        for nr, l in enumerate(linie, 1):
            if not l.startswith(f"| {g['etykieta']} |"):
                continue
            komorka = komorka_kolumny(linie, nr - 1, kolumna) if kolumna else l
            if komorka is None:
                bledy.append((plik, nr, f"(e) wiersz grupy {g['nazwa']} bez kolumny „{kolumna}” w nagłówku tabeli"))
            elif SLOWO_WERDYKTU.search(komorka) or not any(s in komorka for s in BEZ_WERDYKTU):
                bledy.append((plik, nr, f"(e) wiersz grupy {g['nazwa']} (k = {g['k']}) z werdyktem paradygmatów "
                                        f"innym niż undetermined: „{komorka.strip()}”"))
    if len(set((meta.get("tokenizery") or {}).values())) > 1:
        t = por.get(meta.get("porownanie_na_token") or "")
        if not t or t.get("z") is None or not NA_TOKEN.search(tekst):
            bledy.append((plik, 0, "(f) modele z różnymi tokenizerami, a raport nie ma wyniku na token/bajt"))
    return bledy


def komorki(l):
    return [c.strip() for c in l.strip().strip("|").split("|")]


def komorka_kolumny(linie, i, nazwa):
    """Cell of table row linie[i] under header `nazwa` (header = first line of the table block)."""
    j = i
    while j > 0 and linie[j - 1].lstrip().startswith("|"):
        j -= 1
    naglowek = komorki(linie[j])
    if nazwa not in naglowek:
        return None
    wiersz = komorki(linie[i])
    k = naglowek.index(nazwa)
    return wiersz[k] if k < len(wiersz) else ""


def bramka_generatora(meta, liczby, korzen=None):
    """(g) a generated report must equal, byte for byte, the generator output from LICZBY.json: a number,
    verdict or sentence edited by hand, or a stale report after new numbers, gives code 1."""
    import importlib.util
    korzen = korzen or KORZEN
    gen = meta.get("generator")
    if not gen:
        return []
    try:
        spec = importlib.util.spec_from_file_location("_generator_raportu", korzen / gen["modul"])
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        wejscie = json.loads((korzen / gen["wejscie"]).read_text(encoding="utf-8"))
        oczekiwane = getattr(mod, gen["funkcja"])(liczby, wejscie)
    except Exception as e:  # a generator that cannot run from LICZBY.json is a failed gate, not a pass
        return [(meta["plik"], 0, f"(g) generator {gen['modul']} nie działa na LICZBY.json: {type(e).__name__}: {e}")]
    katalog = (korzen / meta["plik"]).parent
    bledy = []
    for nazwa, tresc in sorted(oczekiwane.items()):
        p = katalog / nazwa
        rel = p.relative_to(korzen).as_posix()
        if not p.exists():
            bledy.append((rel, 0, f"(g) brak pliku generowanego przez {gen['modul']}"))
            continue
        jest = p.read_text(encoding="utf-8")
        if jest != tresc:
            a, b = jest.splitlines(), tresc.splitlines()
            nr = next((i for i, (x, y) in enumerate(zip(a, b), 1) if x != y), min(len(a), len(b)) + 1)
            bledy.append((rel, nr, f"(g) plik różni się od wyjścia {gen['modul']} z LICZBY.json (pierwsza różnica "
                                   f"w tej linii); przegeneruj: {gen.get('komenda', 'python benchmarks/blimp/blimp.py raport')}"))
    return bledy


def linie_html(tekst):
    tekst = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", tekst)
    tekst = re.sub(r"(?i)<br\s*/?>|</(p|div|li|tr|h\d|td|th)>", "\n", tekst)
    tekst = html.unescape(re.sub(r"<[^>]+>", " ", tekst))
    return [re.sub(r"[ \t]+", " ", l).strip() for l in tekst.splitlines()]


def pliki_md(korzen):
    for p in sorted(korzen.rglob("*.md")):
        rel = p.relative_to(korzen)
        katalogi = rel.parts[:-1]
        if not POMIN_KATALOGI & set(katalogi) and not any(k.startswith(".") for k in katalogi):
            yield rel.as_posix(), p


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    sciezka_liczb = KORZEN / "results/LICZBY.json"
    if not sciezka_liczb.exists():
        print("brak results/LICZBY.json: najpierw python tools/liczby.py")
        return 2
    liczby = json.loads(sciezka_liczb.read_text())
    zb = zbiory(liczby)
    cele = list(pliki_md(KORZEN)) + [(a, Path(a)) for a in argv]
    bledy, pary = [], 0
    for nazwa, p in cele:
        tekst = p.read_text(encoding="utf-8")
        linie = linie_html(tekst) if p.suffix.lower() in (".html", ".htm") else tekst.splitlines()
        bledy += sprawdz_tekst(nazwa, linie, liczby, zb)
        pary += count_z_verdict_pairs(linie)
    for meta in liczby.get("raporty", []):
        p = KORZEN / meta["plik"]
        if not p.exists():
            bledy.append((meta["plik"], 0, "(d) raport z metadanymi w LICZBY.json nie istnieje"))
            continue
        bledy += bramki_raportu(meta, p.read_text(encoding="utf-8").splitlines(), liczby)
        bledy += bramka_generatora(meta, liczby)
    for plik, nr, powod in bledy:
        print(f"{plik}:{nr}: {powod}")
    print(f"{len(cele)} plików, {len(bledy)} problemów, {pary} par z+werdykt")
    return 1 if bledy else 0


